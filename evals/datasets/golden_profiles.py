"""Golden numeric cases.

Every expected value here was computed by hand from the cited rule, then encoded.
That ordering matters: if the expectation is generated by the code under test, the
test proves only that the code is consistent, not that it is correct.

Expectations reference the DRAFTED rule parameters. When a parameter is verified
and its value changes, the corresponding expectation must be recomputed by hand,
and the test will fail until it is. That failure is the feature.
"""

